describe("every built-in command the router lists runs without the AI", () => {
  it.each(SAID)("%s", (said) => {
    expect(parseCommand(said)).not.toBeNull();
  });
  it("“find next” finds the next match, not the word “next”", () => {
    for (const said of ["find next", "find the next one", "next match"]) expect(parseCommand(said), said).toEqual({ type: "find" });
    expect(parseCommand("find next steps")).toEqual({ type: "find", text: "next steps" });
  });
  it("the list still covers the router's commands (a new one belongs here too)", () => {
    const listed = BUILT_IN_COMMANDS.split(/[;\n]/).length;
    expect(SAID.length).toBeGreaterThanOrEqual(listed);
  });
});
